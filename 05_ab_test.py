# ─────────────────────────────────────────────────────────────────────────────
# HELPER — sample-size calculator (two-proportion z-test)
# ─────────────────────────────────────────────────────────────────────────────

def required_sample_size(p_control: float, p_treatment: float,
                          alpha: float = 0.05, power: float = 0.80) -> int:
    """
    Returns n per group needed to detect the difference between
    p_control and p_treatment at the given alpha and power.
    Uses the standard two-proportion z-test formula.
    """
    z_alpha = norm.ppf(1 - alpha / 2)   # two-tailed
    z_beta  = norm.ppf(power)

    p_bar   = (p_control + p_treatment) / 2
    effect  = abs(p_treatment - p_control)

    numerator   = (z_alpha * math.sqrt(2 * p_bar * (1 - p_bar))
                   + z_beta  * math.sqrt(p_control * (1 - p_control)
                                         + p_treatment * (1 - p_treatment))) ** 2
    denominator = effect ** 2
    return math.ceil(numerator / denominator)


# ─────────────────────────────────────────────────────────────────────────────
# HELPER — two-proportion z-test
# ─────────────────────────────────────────────────────────────────────────────

def two_prop_ztest(n_control: int, conv_control: int,
                   n_treat:   int, conv_treat:   int,
                   alpha: float = 0.05):
    """
    Returns (z_stat, p_value, ci_low, ci_high, significant)
    ci is the 95 % confidence interval on the absolute lift.
    """
    p_c = conv_control / n_control
    p_t = conv_treat   / n_treat

    # Pooled proportion for the z-test
    p_pool = (conv_control + conv_treat) / (n_control + n_treat)
    se_pool = math.sqrt(p_pool * (1 - p_pool) * (1/n_control + 1/n_treat))
    z_stat  = (p_t - p_c) / se_pool
    p_value = 2 * (1 - norm.cdf(abs(z_stat)))   # two-tailed

    # Confidence interval on the raw difference (unpooled SE)
    se_diff = math.sqrt(p_c*(1-p_c)/n_control + p_t*(1-p_t)/n_treat)
    z_ci    = norm.ppf(1 - alpha / 2)
    ci_low  = (p_t - p_c) - z_ci * se_diff
    ci_high = (p_t - p_c) + z_ci * se_diff

    return z_stat, p_value, ci_low, ci_high, p_value < alpha


