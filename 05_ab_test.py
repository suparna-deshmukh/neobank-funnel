FALLBACK_N = 15_000


def make_synthetic(n: int, device_filter: str = None) -> pd.DataFrame:
    """Generate a simple synthetic user table for fallback."""
    devices = np.random.choice(
        ["android", "ios", "web"],
        size=n,
        p=[0.50, 0.30, 0.20]
    )
    if device_filter:
        devices = np.array([device_filter] * n)
    kyc_started   = np.ones(n, dtype=int)
    kyc_completed = np.random.binomial(1, 0.502, size=n)
    return pd.DataFrame({
        "user_id":       [f"sim_{i:06d}" for i in range(n)],
        "device":        devices,
        "kyc_started":   kyc_started,
        "kyc_completed": kyc_completed,
    })


